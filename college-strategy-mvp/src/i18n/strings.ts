function merge(target: Record<string, unknown>, src: Record<string, unknown>, prefix = "") {
  for (const [k, v] of Object.entries(src)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === "object" && !Array.isArray(v)) {
      merge(target, v as Record<string, unknown>, key);
    } else {
      target[key] = v;
    }
  }
}

